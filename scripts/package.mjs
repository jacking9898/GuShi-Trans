import { mkdir, copyFile, cp, rm, readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
const { version } = JSON.parse(await readFile('manifest.json', 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('Invalid manifest version');
const archive = `shiwen-${version}.zip`;
await mkdir('dist', { recursive: true });
const target = 'dist/shiwen';
await rm(target, { recursive: true, force: true });
await mkdir(target);
for (const file of ['manifest.json', 'background.js', 'content.js', 'reader.html', 'reader.js', 'panel.html', 'panel.js', 'options.html', 'options.js', 'styles.css', 'pages.css', 'README.md', 'PRIVACY.md']) await copyFile(file, `${target}/${file}`);
for (const dir of ['lib', 'assets', 'docs']) await cp(dir, `${target}/${dir}`, { recursive: true });
await rm(`dist/${archive}`, { force: true });
const result = spawnSync('zip', ['-q', '-r', archive, 'shiwen'], { cwd: 'dist', stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status || 1);
console.log(`Ready: dist/shiwen/ and dist/${archive}`);
